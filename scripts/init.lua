--Items
Tracker:AddItems("items/items.json")
-- Logic
ScriptHost:LoadScript("scripts/utils.lua")
ScriptHost:LoadScript("scripts/logic/logic.lua")

-- Maps
Tracker:AddMaps("maps/maps.json")
-- Locations
Tracker:AddLocations("locations/locations.json")

-- Layout
Tracker:AddLayouts("layouts/keys.json")
Tracker:AddLayouts("layouts/settings.json")
Tracker:AddLayouts("layouts/items.json")
-- The "All Maps" variant swaps the four map tabs for the single combined map.
-- Tracker.ActiveVariantUID is the variant's key from manifest.json.
if Tracker.ActiveVariantUID == "allmaps" then
	Tracker:AddLayouts("layouts/tabs_allmaps.json")
else
	Tracker:AddLayouts("layouts/tabs.json")
end
Tracker:AddLayouts("layouts/tokens.json")
Tracker:AddLayouts("layouts/snacks.json")
Tracker:AddLayouts("layouts/keyrings.json")
-- layouts/warps.json is intentionally not loaded: the warp grid was dropped in
-- 1.1.0 because warps are already shown on the map. The warp ITEMS still exist
-- (items.json), so the map trapezoids, logic and autotracking are unaffected.
-- To bring the grid back, load this file again and re-add a "Warps" group to
-- layouts/tracker.json.

-- compact.json holds the smaller grids used by tracker_vertical and is
-- generated by tools/make_compact_layouts.py
Tracker:AddLayouts("layouts/compact.json")
-- defines active_keys_grid / active_keys_grid_compact. Must be loaded before
-- tracker.json so the name resolves on the very first render;
-- scripts/keysanity_layout.lua swaps it for the keys or keyrings version.
Tracker:AddLayouts("layouts/active_none.json")
Tracker:AddLayouts("layouts/tracker.json")
Tracker:AddLayouts("layouts/broadcast.json")

-- Show only the key grid matching the Keysanity setting (loads after the
-- layouts above, since it replaces one of them)
ScriptHost:LoadScript("scripts/keysanity_layout.lua")

-- AutoTracking for Poptracker
if PopVersion and PopVersion >= "0.18.0" then
	ScriptHost:LoadScript("scripts/autotracking.lua")
end
